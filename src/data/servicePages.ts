export interface ServicePageLink {
  label: string;
  href: string;
}

export interface ServicePageData {
  /** Public URL: /services/<slug> (and /en/services/<slug>). */
  slug: string;
  /** Card, H1, breadcrumb and Service JSON-LD name. */
  title: string;
  /** Meta description: a shortened sentence from the user's own text. */
  description: string;
  intro: string[];
  listHeading: string;
  items: string[];
  /** Paragraphs after the list (service 3). */
  outro?: string[];
  /** «محصول شاخص» block (service 2), linked to the product page. */
  feature?: { heading: string; text: string; href: string; cta: string };
  /** Extra sections (service 6): heading, lead paragraphs, optional labelled items. */
  sections?: { heading: string; paragraphs: string[]; items?: { label: string; text: string }[]; after?: string[] }[];
  /** Related product and category pages (internal links). */
  related?: ServicePageLink[];
  /** Product ids resolved to their public URL at render time (name from the catalog). */
  relatedProductIds?: string[];
  photo?: SitePhoto;
  /** Card background (decorative). */
  cardImage: string;
}

